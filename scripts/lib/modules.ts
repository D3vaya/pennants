import type { FlagSource } from './flags.ts';

const BANNER = '// Generated by scripts/generate.ts — do not edit.\n';

/** Module exporting a single pennant SVG string (one module per flag keeps it tree-shakable). */
export function flagModule(svg: string): string {
  return `${BANNER}const svg: string = ${JSON.stringify(svg)};\nexport default svg;\n`;
}

export function codesModule(sources: readonly FlagSource[]): string {
  const codes = sources.map((s) => JSON.stringify(s.code)).join(', ');
  const iso = sources
    .filter((s) => s.iso)
    .map((s) => JSON.stringify(s.code))
    .join(', ');
  return (
    BANNER +
    `export const codes = [${codes}] as const;\n` +
    `export type PennantCode = (typeof codes)[number];\n` +
    `export const isoCodes: readonly PennantCode[] = [${iso}];\n`
  );
}

export function namesModule(sources: readonly FlagSource[]): string {
  const entries = sources.map((s) => `  ${JSON.stringify(s.code)}: ${JSON.stringify(s.name)},`);
  return (
    BANNER +
    `import type { PennantCode } from './codes.ts';\n\n` +
    `export const englishNames: Record<PennantCode, string> = {\n${entries.join('\n')}\n};\n`
  );
}

/** Lazy loaders: bundlers turn each `import()` into its own chunk. */
export function loadersModule(sources: readonly FlagSource[]): string {
  const entries = sources.map(
    (s) => `  ${JSON.stringify(s.code)}: () => import(${JSON.stringify(`./flags/${s.code}.ts`)}),`,
  );
  return (
    BANNER +
    `import type { PennantCode } from './codes.ts';\n\n` +
    `export const loaders: Record<PennantCode, () => Promise<{ default: string }>> = {\n${entries.join('\n')}\n};\n`
  );
}
