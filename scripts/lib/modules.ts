import type { ArtSet, FlagArt } from '../../src/shapes.ts';
import type { FlagSource } from './flags.ts';

const BANNER = '// Generated by scripts/generate.ts — do not edit.\n';

export function codesModule(sources: readonly FlagSource[]): string {
  const codes = sources.map((s) => JSON.stringify(s.code)).join(', ');
  const iso = sources
    .filter((s) => s.iso)
    .map((s) => JSON.stringify(s.code))
    .join(', ');
  return (
    BANNER +
    `/**\n` +
    ` * Every available flag code, sorted: ISO 3166-1 alpha-2 countries plus\n` +
    ` * regions and organisations (e.g. \`gb-eng\`, \`es-ct\`, \`eu\`, \`un\`).\n` +
    ` */\n` +
    `export const codes = [${codes}] as const;\n\n` +
    `/** A flag code accepted by every pennants API, e.g. \`'ar'\` or \`'gb-eng'\`. */\n` +
    `export type PennantCode = (typeof codes)[number];\n\n` +
    `/** The subset of {@link codes} that are ISO 3166-1 alpha-2 countries. */\n` +
    `export const isoCodes: readonly PennantCode[] = [${iso}];\n`
  );
}

/**
 * English names of non-ISO flags only (`eu`, `gb-eng`, ...). ISO 3166-1 names
 * come from `Intl.DisplayNames` at runtime, so they cost nothing in bundles.
 */
export function namesModule(sources: readonly FlagSource[]): string {
  const entries = sources
    .filter((s) => !s.iso)
    .map((s) => `  ${JSON.stringify(s.code)}: ${JSON.stringify(s.name)},`);
  return (
    BANNER +
    `import type { PennantCode } from './codes.ts';\n\n` +
    `export const extraNames: Partial<Record<PennantCode, string>> = {\n${entries.join('\n')}\n};\n`
  );
}

/**
 * Module exporting one flag's artwork for a set. JS ships artwork rather than
 * framed SVG, so a flag is bundled once however many shapes an app uses.
 * The type is spelled out (structurally `FlagArt`) so each emitted `.d.ts`
 * is self-contained instead of importing a private shared chunk.
 */
export function artModule(art: FlagArt): string {
  return (
    BANNER +
    `const art: { code: string; viewBox: string; content: string } = ${JSON.stringify(art)};\n` +
    `export default art;\n`
  );
}

/** Lazy artwork loaders of one set (`loaders-<set>.ts`), one chunk per flag. */
export function artLoadersModule(sources: readonly FlagSource[], set: ArtSet): string {
  const entries = sources.map(
    (s) =>
      `  ${JSON.stringify(s.code)}: () => import(${JSON.stringify(`./art/${set}/${s.code}.ts`)}),`,
  );
  return (
    BANNER +
    `import type { FlagArt } from '../shapes.ts';\n` +
    `import type { PennantCode } from './codes.ts';\n\n` +
    `/** Lazy loaders of the \`${set}\` artwork, one chunk per flag. */\n` +
    `export const loaders: Record<PennantCode, () => Promise<{ default: FlagArt }>> = {\n${entries.join('\n')}\n};\n`
  );
}
