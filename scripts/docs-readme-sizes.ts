/**
 * Renders the README weight table from docs/data/bundle-sizes.json (the
 * bundle-budget snapshot), between the `sizes:start` / `sizes:end` markers.
 * npm cannot render the docs' <Size> components, so the README gets a
 * generated copy instead of hand-written numbers.
 *
 *   node scripts/docs-readme-sizes.ts           rewrite README.md
 *   node scripts/docs-readme-sizes.ts --check   exit 1 if README.md is stale
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import { format, resolveConfig } from 'prettier';

interface Triple {
  min: number;
  gzip: number;
  brotli: number;
}
interface Probe {
  entry: Triple;
  css: Triple | null;
  lazyFiles: number;
}
interface Snapshot {
  vite: string;
  probes: Record<string, Probe>;
}

const root = fileURLToPath(new URL('..', import.meta.url));
const readmePath = join(root, 'README.md');
const snapshot = JSON.parse(
  await readFile(join(root, 'docs', 'data', 'bundle-sizes.json'), 'utf8'),
) as Snapshot;

const kb = (bytes: number): string =>
  bytes < 1000 ? `${bytes} B` : `${(bytes / 1000).toFixed(1)} kB`;

function probe(name: string): Probe {
  const value = snapshot.probes[name];
  if (!value) throw new Error(`Missing probe "${name}" in docs/data/bundle-sizes.json`);
  return value;
}

/** [label, probe name, note on the size] for each README row. */
const rows: [string, string, string][] = [
  ['CSS classes, `assetsInlineLimit` set ¹', 'css', 'CSS'],
  ['CSS classes, `pennants/css/cdn` ²', 'css-cdn', 'CSS'],
  ['One flag, static import (`pennants/art/1x1/ar`)', 'art-pennant', 'JS'],
  ['`getPennantName`', 'name', 'JS'],
  ['`fetchPennant` (`pennants/fetch`)', 'fetch', 'JS'],
  ['`loadFlag` / `loadPennant`', 'load', 'JS'],
  ['React `<Pennant>`', 'react-pennant', 'JS'],
  ['`<pennant-flag>`', 'element', 'JS'],
];

const lines = [
  `Measured with Vite ${snapshot.vite} (production build, difference against an empty app, gzip).`,
  'Generated from `npm run bundle:budget`; see the docs for min and brotli.',
  '',
  '| You use | Added up front | Lazy files ³ |',
  '| ------- | -------------- | ------------ |',
  '| `<img>` / CDN, PNG | 0 | 0 |',
  ...rows.map(([label, name, kind]) => {
    const value = probe(name);
    const size = kind === 'CSS' ? value.css?.gzip : value.entry.gzip;
    if (size === undefined) throw new Error(`Probe "${name}" has no ${kind} size`);
    return `| ${label} | ${kb(size)} ${kind} | ${value.lazyFiles} |`;
  }),
  '',
  `¹ With Vite's defaults every flag is inlined into the CSS (${kb(probe('css-default').css?.gzip ?? 0)} gzip); see the`,
  '[FAQ](https://d3vaya.github.io/pennants/guide/faq#bundler-asset-imports). Next.js and Angular do',
  'not inline.',
  '² Same classes, with flag URLs pointing at jsDelivr (version-pinned); bundlers leave them alone.',
  '³ Emitted into your build, downloaded only when that flag is shown.',
];

const start = '<!-- sizes:start (generated by scripts/docs-readme-sizes.ts) -->';
const end = '<!-- sizes:end -->';
const readme = await readFile(readmePath, 'utf8');
const from = readme.indexOf(start);
const to = readme.indexOf(end);
if (from === -1 || to === -1) throw new Error('README.md is missing the sizes markers');
// Format like the rest of the repo so `prettier --check` and `--check` agree.
const next = await format(
  `${readme.slice(0, from + start.length)}\n\n${lines.join('\n')}\n\n${readme.slice(to)}`,
  { ...(await resolveConfig(readmePath)), filepath: readmePath },
);

if (process.argv.includes('--check')) {
  if (next !== readme) {
    console.error('README.md sizes are stale. Run `node scripts/docs-readme-sizes.ts`.');
    process.exit(1);
  }
  console.info('README.md sizes match the snapshot');
} else {
  await writeFile(readmePath, next);
  console.info('Updated the README.md sizes table');
}
